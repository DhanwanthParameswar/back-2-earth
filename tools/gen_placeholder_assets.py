#!/usr/bin/env python3
"""Generate Back2Earth's placeholder pixel art and chiptune sound effects.

Owner: D. Everything here is original and generated by this script, so there
is nothing to license. Replace any file with real art at the SAME size and the
game picks it up; collisions never depend on art.

Pixel scale: props and tiles are drawn at 16 px per tile and saved at 2x, so
one art pixel = 2x2 screen pixels, matching the astronaut skins
(tools/import_astronaut_skins.py).

    pip install pillow numpy
    python3 tools/gen_placeholder_assets.py

Palette: PICO-8 16 colors (navy ship, cyan interactions, amber warnings, red hazards).
"""
from __future__ import annotations

import math
import random
import wave
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "assets"

P = {
    "black": (0, 0, 0, 255), "navy": (29, 43, 83, 255), "purple": (126, 37, 83, 255),
    "dgreen": (0, 135, 81, 255), "brown": (171, 82, 54, 255), "dgray": (95, 87, 79, 255),
    "lgray": (194, 195, 199, 255), "white": (255, 241, 232, 255), "red": (255, 0, 77, 255),
    "orange": (255, 163, 0, 255), "yellow": (255, 236, 39, 255), "green": (0, 228, 54, 255),
    "blue": (41, 173, 255, 255), "indigo": (131, 118, 156, 255), "pink": (255, 119, 168, 255),
    "peach": (255, 204, 170, 255), "clear": (0, 0, 0, 0),
}


def img(w: int, h: int, fill: str = "clear") -> tuple[Image.Image, ImageDraw.ImageDraw]:
    im = Image.new("RGBA", (w, h), P[fill])
    return im, ImageDraw.Draw(im)


def save(im: Image.Image, rel: str) -> None:
    path = ASSETS / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    im.save(path)
    print("wrote", path.relative_to(ROOT))


# --- Tiles and props -------------------------------------------------------------------
# Drawn at 16 px per tile ("art pixels") and saved at 2x, so every art pixel is
# 2x2 screen pixels: the same pixel size as the astronaut skins.

def save2x(im: Image.Image, rel: str) -> None:
    save(im.resize((im.width * 2, im.height * 2), Image.NEAREST), rel)


FLOOR_LINE = (22, 32, 64, 255)
CAP = (58, 56, 72, 255)
CAP_EDGE = (95, 92, 112, 255)
FACE = (84, 92, 122, 255)
FACE_LIGHT = (112, 122, 156, 255)
FACE_DARK = (40, 44, 64, 255)


def floor_tile() -> None:
    im, d = img(16, 16, "navy")
    d.line([0, 0, 15, 0], fill=FLOOR_LINE)
    d.line([0, 0, 0, 15], fill=FLOOR_LINE)
    d.line([0, 8, 15, 8], fill=(25, 37, 72, 255))
    for x, y in [(3, 3), (12, 3), (3, 12), (12, 12)]:
        d.point((x, y), fill=(52, 64, 112, 255))
    save2x(im, "tiles/floor.png")


def wall_tiles() -> None:
    # Top of a wall seen from above (3/4 view): dark cap with a lit edge.
    im, d = img(16, 16)
    d.rectangle([0, 0, 15, 15], fill=CAP)
    d.line([0, 0, 15, 0], fill=CAP_EDGE)
    d.line([0, 15, 15, 15], fill=(30, 30, 40, 255))
    for x, y in [(3, 4), (12, 4), (3, 11), (12, 11)]:
        d.point((x, y), fill=CAP_EDGE)
    save2x(im, "tiles/wall.png")

    # Front faces (the side facing the camera). Three variants:
    #   wall_face_single  one tile tall: cap lip + panel + baseboard
    #   wall_face_upper   top of a 2-tile face: cap lip + panel
    #   wall_face         bottom of a 2-tile face: panel + baseboard
    def face(lip: bool, base: bool) -> Image.Image:
        im, d = img(16, 16)
        top = 0
        if lip:
            d.rectangle([0, 0, 15, 2], fill=CAP)
            d.line([0, 0, 15, 0], fill=CAP_EDGE)
            top = 3
        bottom = 13 if base else 15
        d.rectangle([0, top, 15, bottom], fill=FACE)
        if lip:
            d.line([0, top, 15, top], fill=FACE_LIGHT)
        d.line([7, top + 1, 7, bottom], fill=FACE_DARK)
        if base:
            d.rectangle([0, 14, 15, 15], fill=FACE_DARK)
        return im

    im = face(True, True)
    ImageDraw.Draw(im).point((3, 7), fill=P["orange"])
    save2x(im, "tiles/wall_face_single.png")
    im = face(False, True)
    ImageDraw.Draw(im).point((3, 5), fill=P["orange"])
    save2x(im, "tiles/wall_face.png")

    # Upper half of a 2-tile-tall wall face (Stardew-style back wall), with a vent.
    im = face(True, False)
    d = ImageDraw.Draw(im)
    d.rectangle([10, 7, 13, 11], fill=(52, 60, 92, 255))
    for y in (8, 10):
        d.line([10, y, 13, y], fill=FACE_DARK)
    save2x(im, "tiles/wall_face_upper.png")


def window_tile() -> None:
    im, d = img(16, 16)
    d.rectangle([0, 0, 15, 15], outline=CAP_EDGE)
    d.rectangle([1, 1, 14, 14], outline=CAP)
    d.line([2, 2, 4, 2], fill=(255, 255, 255, 110))
    d.line([2, 2, 2, 4], fill=(255, 255, 255, 110))
    save2x(im, "tiles/window.png")


def rail_tile() -> None:
    im, d = img(16, 16)
    d.rectangle([0, 0, 15, 15], fill=(14, 20, 40, 255))
    d.line([4, 0, 4, 15], fill=P["dgray"])
    d.line([11, 0, 11, 15], fill=P["dgray"])
    for y in range(1, 16, 4):
        d.line([3, y, 12, y], fill=(40, 40, 52, 255))
    save2x(im, "tiles/rail.png")


def door_tiles() -> None:
    im, d = img(16, 16, "dgray")
    d.rectangle([1, 1, 14, 14], fill=(40, 38, 46, 255))
    for i in range(-16, 16, 5):  # amber hazard stripes
        d.line([i, 15, i + 15, 0], fill=P["orange"], width=2)
    d.rectangle([0, 0, 15, 0], fill=CAP_EDGE)
    d.rectangle([0, 15, 15, 15], fill=FACE_DARK)
    d.rectangle([6, 6, 9, 9], fill=P["red"])  # locked light
    save2x(im, "tiles/door_closed.png")

    im, d = img(16, 16, "navy")
    d.line([0, 0, 15, 0], fill=FLOOR_LINE)
    d.rectangle([0, 0, 1, 15], fill=CAP)
    d.rectangle([14, 0, 15, 15], fill=CAP)
    d.rectangle([7, 7, 8, 8], fill=P["green"])
    save2x(im, "tiles/door_open.png")


def console(name: str, screen: str, accent: str) -> None:
    # 3/4 view: screen on top, body facing the camera, feet on the floor.
    im, d = img(16, 16)
    d.rectangle([1, 7, 14, 15], fill=P["dgray"])
    d.line([1, 7, 14, 7], fill=P["lgray"])
    d.rectangle([2, 1, 13, 7], fill=P["black"])
    d.rectangle([3, 2, 12, 6], fill=P[screen])
    d.line([4, 3, 9, 3], fill=P["navy"])
    d.line([4, 5, 7, 5], fill=P["navy"])
    d.rectangle([3, 9, 4, 10], fill=P[accent])
    d.rectangle([7, 9, 8, 10], fill=P["lgray"])
    d.rectangle([11, 9, 12, 10], fill=P[accent])
    d.line([1, 15, 14, 15], fill=FACE_DARK)
    save2x(im, f"sprites/{name}.png")


def crate() -> None:
    im, d = img(16, 16)
    d.rectangle([1, 2, 14, 15], fill=P["brown"], outline=P["black"])
    d.rectangle([1, 2, 14, 5], fill=(205, 112, 70, 255), outline=P["black"])  # lid seen from above
    d.line([3, 7, 12, 13], fill=P["orange"])
    d.line([12, 7, 3, 13], fill=P["orange"])
    save2x(im, "sprites/crate.png")


def plates() -> None:
    for name, light in (("plate", "red"), ("plate_on", "green")):
        im, d = img(16, 16)
        d.rectangle([1, 1, 14, 14], fill=P["dgray"], outline=P["black"])
        d.rectangle([3, 3, 12, 12], fill=P["lgray"])
        d.rectangle([7, 7, 8, 8], fill=P[light])
        save2x(im, f"sprites/{name}.png")


def core() -> None:
    im, d = img(8, 8)
    d.ellipse([0, 0, 7, 7], fill=P["navy"], outline=P["blue"])
    d.rectangle([2, 2, 5, 5], fill=P["blue"])
    d.point((3, 3), fill=P["white"])
    save2x(im, "sprites/core.png")


def pod() -> None:
    im, d = img(32, 32)
