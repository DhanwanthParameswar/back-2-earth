#!/usr/bin/env python3
"""Generate Back2Earth's placeholder pixel art and chiptune sound effects.

Owner: D. Everything here is original and generated by this script, so there
is nothing to license. Replace any file with real art at the SAME size and the
game picks it up; collisions never depend on art.

    pip install pillow numpy
    python3 tools/gen_placeholder_assets.py

Palette: PICO-8 16 colors (navy ship, cyan interactions, amber warnings, red hazards).
"""
from __future__ import annotations

import math
import random
import wave
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "assets"

P = {
    "black": (0, 0, 0, 255), "navy": (29, 43, 83, 255), "purple": (126, 37, 83, 255),
    "dgreen": (0, 135, 81, 255), "brown": (171, 82, 54, 255), "dgray": (95, 87, 79, 255),
    "lgray": (194, 195, 199, 255), "white": (255, 241, 232, 255), "red": (255, 0, 77, 255),
    "orange": (255, 163, 0, 255), "yellow": (255, 236, 39, 255), "green": (0, 228, 54, 255),
    "blue": (41, 173, 255, 255), "indigo": (131, 118, 156, 255), "pink": (255, 119, 168, 255),
    "peach": (255, 204, 170, 255), "clear": (0, 0, 0, 0),
}


def img(w: int, h: int, fill: str = "clear") -> tuple[Image.Image, ImageDraw.ImageDraw]:
    im = Image.new("RGBA", (w, h), P[fill])
    return im, ImageDraw.Draw(im)


def save(im: Image.Image, rel: str) -> None:
    path = ASSETS / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    im.save(path)
    print("wrote", path.relative_to(ROOT))


# --- Tiles (32x32) ----------------------------------------------------------------

def floor_tile() -> None:
    im, d = img(32, 32, "navy")
    d.rectangle([0, 0, 31, 31], outline=(22, 32, 64, 255))
    d.line([0, 15, 31, 15], fill=(22, 32, 64, 255))
    d.line([15, 0, 15, 31], fill=(22, 32, 64, 255))
    for x, y in [(3, 3), (28, 3), (3, 28), (28, 28)]:
        d.point((x, y), fill=P["indigo"])
    save(im, "tiles/floor.png")


