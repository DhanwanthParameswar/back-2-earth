def debris() -> None:
    im, d = img(12, 12)
    pts = [(1, 4), (4, 1), (7, 2), (10, 1), (10, 6), (11, 10), (6, 10), (3, 9), (1, 7)]
    d.polygon(pts, fill=P["dgray"], outline=P["red"])
    d.line([3, 4, 7, 7], fill=P["red"])
    d.point((6, 3), fill=P["lgray"])
    save2x(im, "sprites/debris.png")


def echo_portrait() -> None:
    im, d = img(16, 16, "black")
    d.rectangle([0, 0, 15, 15], outline=P["blue"])
    for i, h in enumerate([1, 3, 5, 3, 6, 2, 4, 2]):
        x = 2 + i + (i // 2)
        d.line([x, 8 - h, x, 8 + h], fill=P["blue"])
    d.point((13, 2), fill=P["red"])  # damaged indicator
    save2x(im, "sprites/echo.png")


# --- Backdrops (drawn small, scaled 2x with nearest neighbor) --------------------------

def black_hole() -> None:
    w, h = 320, 180
    im, d = img(w, h, "black")
    rng = random.Random(7)
    for _ in range(140):
        x, y = rng.randrange(w), rng.randrange(h)
        d.point((x, y), fill=P[rng.choice(["white", "lgray", "indigo", "blue"])])
    cx, cy = 200, 90
    # Accretion disk: squashed rings, hot inside to cool outside.
    for r, color in ((70, "purple"), (60, "red"), (50, "orange"), (42, "yellow"), (36, "orange")):
        d.ellipse([cx - r, cy - r // 3, cx + r, cy + r // 3], outline=P[color], width=3)
    # Photon ring + event horizon.
    d.ellipse([cx - 26, cy - 26, cx + 26, cy + 26], fill=P["orange"])
    d.ellipse([cx - 23, cy - 23, cx + 23, cy + 23], fill=P["black"])
    # Front of the disk passes in front of the hole.
    d.rectangle([cx - 60, cy - 2, cx + 60, cy + 2], fill=P["orange"])
    d.rectangle([cx - 40, cy - 1, cx + 40, cy + 1], fill=P["yellow"])
    save(im.resize((w * 2, h * 2), Image.NEAREST), "backdrops/black_hole.png")


def earth() -> None:
    s = 64
    im, d = img(s, s)
    d.ellipse([1, 1, s - 2, s - 2], fill=P["blue"])
    rng = random.Random(42)
    cx = cy = s / 2
    for _ in range(9):  # continents
        x, y = rng.randrange(12, 52), rng.randrange(12, 52)
        rw, rh = rng.randrange(4, 11), rng.randrange(3, 8)
        d.ellipse([x - rw, y - rh, x + rw, y + rh], fill=P["green"] if rng.random() > 0.3 else P["dgreen"])
    for _ in range(6):  # clouds
        x, y = rng.randrange(8, 56), rng.randrange(8, 56)
        d.line([x - 5, y, x + 5, y], fill=P["white"], width=2)
    # Mask to a circle, add night side.
    px = im.load()
    for y in range(s):
        for x in range(s):
            dist = math.hypot(x - cx + 0.5, y - cy + 0.5)
            if dist > s / 2 - 1:
                px[x, y] = P["clear"]
            elif x + y > s * 1.25:
                r, g, b, a = px[x, y]
                px[x, y] = (r // 3, g // 3, b // 2, a)
    save(im.resize((s * 2, s * 2), Image.NEAREST), "backdrops/earth.png")


# --- Sound (22.05 kHz, 16-bit mono WAV) -------------------------------------------------

SR = 22050


def square(freq: float, dur: float, vol: float = 0.4) -> np.ndarray:
    t = np.arange(int(SR * dur)) / SR
    return vol * np.sign(np.sin(2 * np.pi * freq * t))


def env(x: np.ndarray, attack: float = 0.005, release: float = 0.05) -> np.ndarray:
    n = len(x)
    e = np.ones(n)
    a, r = int(SR * attack), int(SR * release)
    if a:
        e[:a] = np.linspace(0, 1, a)
    if r:
        e[-r:] = np.minimum(e[-r:], np.linspace(1, 0, r))
    return x * e


def silence(dur: float) -> np.ndarray:
    return np.zeros(int(SR * dur))


def write_wav(rel: str, x: np.ndarray) -> None:
    path = ASSETS / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    data = (np.clip(x, -1, 1) * 32767 * 0.8).astype("<i2")
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(data.tobytes())
    print("wrote", path.relative_to(ROOT))


def sounds() -> None:
    rng = np.random.default_rng(3)
    beep = lambda f: env(square(f, 0.11, 0.35))  # noqa: E731
    write_wav("audio/warning.wav", np.concatenate([beep(880), silence(0.06), beep(660), silence(0.06), beep(880)]))

    t = np.arange(int(SR * 0.14)) / SR
    thunk = 0.5 * np.sign(np.sin(2 * np.pi * 110 * t)) * np.exp(-t * 30)
    write_wav("audio/boots.wav", env(thunk, release=0.02))

    n = int(SR * 0.28)
    noise = rng.uniform(-1, 1, n)
    noise = np.convolve(noise, np.ones(6) / 6, mode="same") * np.exp(-np.arange(n) / SR * 14)
    write_wav("audio/hit.wav", 0.9 * noise)

    notes = [523.25, 659.25, 783.99, 1046.5]
    write_wav("audio/objective.wav", np.concatenate([env(square(f, 0.08, 0.3), release=0.02) for f in notes]))

    t = np.arange(int(SR * 0.35)) / SR
    freq = np.linspace(200, 520, len(t))
    sweep = 0.3 * np.sign(np.sin(2 * np.pi * np.cumsum(freq) / SR))
    write_wav("audio/door.wav", env(sweep, release=0.08))

    t = np.arange(int(SR * 1.4)) / SR
    freq = np.linspace(80, 900, len(t))
    tone = 0.25 * np.sign(np.sin(2 * np.pi * np.cumsum(freq) / SR))
    rumble = 0.35 * rng.uniform(-1, 1, len(t)) * np.linspace(1, 0.2, len(t))
    write_wav("audio/launch.wav", env(tone + rumble, attack=0.05, release=0.3))

    # Seamless 4 s ship hum: whole numbers of cycles for every component.
    t = np.arange(int(SR * 4.0)) / SR
    hum = 0.22 * np.sin(2 * np.pi * 55 * t) + 0.1 * np.sin(2 * np.pi * 110 * t)
    hum *= 0.8 + 0.2 * np.sin(2 * np.pi * 0.5 * t)
    write_wav("audio/ambient_hum.wav", hum)


def main() -> None:
    floor_tile(); wall_tiles(); window_tile(); rail_tile(); door_tiles()
    console("terminal", "blue", "blue")
    console("power_console", "orange", "orange")
    console("clamp_console", "yellow", "orange")
    crate(); plates(); core(); pod(); debris(); echo_portrait()
    black_hole(); earth()
    sounds()


if __name__ == "__main__":
    main()
