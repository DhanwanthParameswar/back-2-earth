#!/usr/bin/env python3
"""Recover the timing of the team's final intro cut. Owner: D.
Needs ffmpeg on PATH and: pip install pillow numpy scipy

The final cut (assets/video/intro.ogv, edited outside the repo with the voices)
is the footage tools/make_intro.py draws, re-timed in a few places (a longer
year card, a frame nudge in the dashboard shot, 1.4 s cut from the outside
shot). This finds, for every frame of the final cut, which frame of the
original render it shows, and writes that list to data/intro_edit_map.json.
The in-game film (scripts/ui/intro_film.gd) plays the original frames in that
order, so it matches the final cut and its voice track frame for frame.

    python3 tools/align_intro_edit.py
"""
from __future__ import annotations

import json
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import make_intro as mi  # noqa: E402

FINAL = ROOT / "assets/video/intro.ogv"
OUT = ROOT / "data/intro_edit_map.json"
JUMP = 6.0   # cost of an edit cut
HOLD = 0.5   # cost of showing the same frame again


def small(a: np.ndarray) -> np.ndarray:
    n = a.shape[0]
    return a.reshape(n, 90, 2, 160, 2, 3).mean((2, 4))


def main() -> None:
    mi.build_globals()
    cast = mi.cast_for("classic")
    n_base = int(round(mi.LENGTH * mi.FPS))
    base = np.stack([mi.scene_frame(i / mi.FPS, cast) for i in range(n_base)]).astype(np.float32)
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(FINAL), "-vf", "scale=320:180:flags=area",
                        str(Path(tmp) / "f%04d.png")], check=True)
        files = sorted(Path(tmp).glob("f*.png"))
        final = np.stack([np.asarray(Image.open(f).convert("RGB")) for f in files]).astype(np.float32)
    bs, fs = small(base), small(final)
    n, m = len(fs), len(bs)
    # Dynamic programming: each final frame is the next base frame, the same one
    # again, or (at an edit) any base frame.
    cost = np.stack([np.abs(bs - fs[i]).mean((1, 2, 3)) for i in range(n)]).astype(np.float32)
    total = cost[0] + np.where(np.arange(m) == 0, 0, JUMP)
    back = np.zeros((n, m), np.int32)
    for i in range(1, n):
        prev = total
        best = int(prev.argmin())
        cont = np.full(m, np.inf, np.float32)
        cont[1:] = prev[:-1]
        opts = np.stack([cont, prev + HOLD, np.full(m, prev[best] + JUMP, np.float32)])
        k = opts.argmin(0)
        total = opts[k, np.arange(m)] + cost[i]
        back[i] = np.where(k == 0, np.arange(m) - 1, np.where(k == 1, np.arange(m), best))
    j = int(total.argmin())
    path = [j]
    for i in range(n - 1, 0, -1):
        j = int(back[i, j])
        path.append(j)
    path = path[::-1]
    err = cost[np.arange(n), path]
    OUT.write_text(json.dumps({
        "_note": "Generated by tools/align_intro_edit.py: for each frame of the final cut "
                 "(30 fps), the frame of tools/make_intro.py's render it shows.",
        "fps": mi.FPS,
        "frames": [int(x) for x in path],
    }) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {n} frames, mean error {err.mean():.2f} (compression noise)")


if __name__ == "__main__":
    main()
